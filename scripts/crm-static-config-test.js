const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'public/admin/index.html'),'utf8');
const code=fs.readFileSync(path.join(root,'public/admin/public-config.js'),'utf8');
const js=fs.readFileSync(path.join(root,'public/admin/crm.js'),'utf8');
const ctx={window:{}};
vm.runInNewContext(code,ctx,{timeout:1000});
const cfg=ctx.window.AB_STUDIO_CRM_PUBLIC_CONFIG;
assert.ok(cfg,'Public config must load from static file');
assert.match(cfg.projectUrl,/^https:\/\/[a-z0-9-]+\.supabase\.co$/i);
assert.ok(cfg.publishableKey.startsWith('sb_publishable_'));
assert.ok(!code.includes('sb_secret_'),'Never embed a secret API key');
assert.ok(!code.includes('SUPABASE_SECRET_KEY'),'Do not reference server secret in browser config');
assert.ok(html.indexOf('src="/admin/public-config.js"') < html.indexOf('src="/admin/crm.js"'),'Public config must execute first');
assert.match(js,/window\.AB_STUDIO_CRM_PUBLIC_CONFIG/);
assert.match(js,/if\(!config\) try\{/);
console.log('CRM static public configuration tests passed.');
