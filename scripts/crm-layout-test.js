const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'public/admin/index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'public/admin/crm.js'),'utf8');
const css=fs.readFileSync(path.join(root,'public/admin/crm.css'),'utf8');
const nav=html.match(/<nav class="crm-sidebar-nav"[\s\S]*?<\/nav>/)?.[0];
assert.ok(nav,'CRM must have sidebar navigation');
assert.deepEqual([...nav.matchAll(/data-crm-view="([^"]+)"/g)].map(x=>x[1]),['overview','leads'],'Only the essential CRM sections should appear');
const overviewAt=html.indexOf('id="view-overview"');
const leadsAt=html.indexOf('id="view-leads"');
assert.ok(overviewAt>-1 && leadsAt>overviewAt,'Summary and leads must have separate content');
const overview=html.slice(overviewAt,leadsAt),leads=html.slice(leadsAt,html.indexOf('id="notice"'));
assert.ok(overview.includes('id="metrics"'),'Overview must show CRM KPIs');
assert.ok(overview.includes('id="recent-leads"'),'Overview must show recent leads');
assert.ok(!overview.includes('id="filter"'),'Stage filter belongs to Leads, not Overview');
assert.ok(leads.includes('id="filter"') && leads.includes('>Stage<select'),'Leads must own the Stage filter');
assert.ok(leads.includes('id="search"') && leads.includes('id="leads"'));
assert.ok(js.includes("setActiveView('leads')"),'Recent inquiries must navigate to Leads');
assert.ok(js.includes("$('#refresh-leads').addEventListener('click',load)"),'Both sections must refresh');
assert.ok(js.includes("document.body.classList.toggle('crm-workspace-open'"),'Unauthenticated screens must keep their existing layout');
assert.ok(css.includes('@media(max-width:950px)') && css.includes('.crm-shell{display:grid'),'Sidebar must adapt to mobile');
console.log('CRM sidebar layout and navigation tests passed.');
